  function unique(items) {
    var seen = {};
    return (items || []).filter(function(item) {
      var key = String(item || '').trim();
      if (!key || seen[key]) return false;
      seen[key] = true;
      return true;
    });
  }

  function normalizeText(text) {
    var normalized = String(text || '');
    NORMALIZATIONS.forEach(function(pair) {
      normalized = normalized.split(pair[0]).join(pair[1]);
    });
    return normalized.replace(/\s+/g, ' ').trim();
  }

  function extractAliases(text, aliasMap) {
    // 英文别名大小写不敏感：知识库标题里 IMEI / imei / WiFi / wifi 混用，
    // 大小写敏感会让「安卓imei判定方式」这类标题一条都命中不了。
    var normalized = normalizeText(text).toLowerCase();
    var matches = [];
    Object.keys(aliasMap).forEach(function(canonical) {
      var aliases = aliasMap[canonical];
      if (aliases.some(function(alias) {
        return normalized.indexOf(normalizeText(alias).toLowerCase()) !== -1;
      })) {
        matches.push(canonical);
      }
    });
    return unique(matches);
  }

  function extractParts(text) {
    return extractAliases(text, PART_ALIASES);
  }

  function extractPhenomena(text) {
    return extractAliases(text, PHENOMENON_ALIASES);
  }

  function extractCategories(text) {
    return extractAliases(text, CATEGORY_ALIASES);
  }

  function extractNegativeTerms(text) {
    var normalized = normalizeText(text);
    var negatives = [];
    function collectNegativeAliases(aliasMap) {
      Object.keys(aliasMap).forEach(function(canonical) {
        aliasMap[canonical].forEach(function(alias) {
          var term = normalizeText(alias);
          if (
            normalized.indexOf('不是' + term) !== -1 ||
            normalized.indexOf('不属于' + term) !== -1 ||
            normalized.indexOf('排除' + term) !== -1
          ) {
            negatives.push(canonical);
          }
        });
      });
    }
    collectNegativeAliases(PART_ALIASES);
    collectNegativeAliases(PHENOMENON_ALIASES);
    return unique(negatives);
  }

  function isGenericTerm(term) {
    var normalized = normalizeText(term).replace(/[，。！？,.!?\s]/g, '');
    if (!normalized) return true;
    return GENERIC_TERMS.some(function(generic) {
      return normalized === generic;
    });
  }

  function arePartsConflicting(queryParts, entryParts) {
    var left = unique(queryParts);
    var right = unique(entryParts);
    if (!left.length || !right.length) return false;
    return !left.some(function(part) {
      return right.indexOf(part) !== -1;
    });
  }

